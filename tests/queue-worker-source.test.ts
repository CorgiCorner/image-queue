import {mkdtemp,copyFile,writeFile,rm,mkdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {afterEach,expect,it} from 'vitest';
import sharp from 'sharp';
import {MemoryStorage} from '../src/storage/memory';
import {queueWorkerSource} from '../src/storage/queue-worker-source';
import {appendQueue} from '../src/sources/queue';
import {hash,type Job} from '../src/core/schema';
const roots:string[]=[];afterEach(async()=>{await Promise.all(roots.splice(0).map(r=>rm(r,{recursive:true,force:true})));});
it('claims and publishes through the original helper, preserving the queue protocol',async()=>{
 const root=await mkdtemp(join(tmpdir(),'iq-source-'));roots.push(root);await copyFile(resolve('docs/protocol/worker.py'),join(root,'worker.py'));await writeFile(join(root,'images-todo.md'),'# Image requests\n');
 const store=new MemoryStorage();const job={id:'IMG-source-check',idempotencyKey:'source-check',projectId:'p',prompt:'A blue square',source:'queue',provider:'openai',model:'',width:32,height:32,transparent:false,referenceIds:[],status:'queued',requestHash:'hash',createdAt:new Date().toISOString()} as unknown as Job;
 await appendQueue(root,job,[]);await store.put('jobs',job.id,job);
 const source=queueWorkerSource(store,{queueRoot:root,workerId:'local-one',model:'gpt-6.1-sol',effort:'low'});const c=await source.claim('local-one',['codex-image']);expect(c?.job.prompt).toBe(job.prompt);
 const bytes=await sharp({create:{width:32,height:32,channels:3,background:'blue'}}).png().toBuffer();const blobKey=await hash(bytes);await store.putBlob(blobKey,bytes,'image/png');
 const image=join(root,'fitted.png'),receipt=join(root,'receipt.json'),provenance=join(root,'provenance.md');await writeFile(receipt,JSON.stringify({prompt:job.prompt,referencePaths:[],attachment:null,workerInstructionsVersion:'image-queue-worker-v2'}));await writeFile(provenance,'generated by fixture');await store.put('generation-artifacts',job.id,{image,receipt,provenance});
 await source.start(job.id,c!.leaseId);
 await source.complete(job.id,c!.leaseId,{blobKey,width:32,height:32,mime:'image/png'});
 expect(await source.claim('local-one',['codex-image'])).toBeNull();
 expect(await store.get('jobs',job.id)).toMatchObject({status:'done',blobKey});
 expect((await store.get<Job>('jobs',job.id))?.claim).toBeUndefined();
});
