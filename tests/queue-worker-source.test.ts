it('resumes an application reservation without launch evidence after restart',async()=>{
 const root=await mkdtemp(join(tmpdir(),'iq-source-'));roots.push(root);await copyFile(resolve('docs/protocol/worker.py'),join(root,'worker.py'));await writeFile(join(root,'images-todo.md'),'# Image requests\n');
 const store=new MemoryStorage();const job={id:'IMG-recovery',prompt:'A square',width:32,height:32,transparent:false,referenceIds:[]} as unknown as Job;await appendQueue(root,job,[]);
 const first=queueWorkerSource(store,{queueRoot:root,workerId:'local:first',model:'gpt-6.1-sol',effort:'low'});await first.claim('local:first',['codex-image']);
 // Simulate a crash before execution: discard only the application lease, never the file reservation.
 for(const l of await store.entries('runner-leases'))await store.delete('runner-leases',l.id);
 const successor=queueWorkerSource(store,{queueRoot:root,workerId:'local:second',model:'gpt-6.1-sol',effort:'low'});
 expect((await successor.claim('local:second',['codex-image']))?.job.id).toBe(job.id);
});
it('rejects result content whose hash or dimensions do not match publication metadata',async()=>{
 const root=await mkdtemp(join(tmpdir(),'iq-content-'));roots.push(root);await copyFile(resolve('docs/protocol/worker.py'),join(root,'worker.py'));await writeFile(join(root,'images-todo.md'),'# Image requests\n');
 const store=new MemoryStorage();const job={id:'IMG-content',prompt:'A square',width:32,height:32,transparent:false,referenceIds:[]} as unknown as Job;await appendQueue(root,job,[]);
 const source=queueWorkerSource(store,{queueRoot:root,workerId:'local:a',model:'gpt-6.1-sol',effort:'low'});const claim=(await source.claim('local:a',['codex-image']))!;await source.start(job.id,claim.leaseId);
 await store.put('generation-artifacts',job.id,{image:join(root,'result.png'),receipt:join(root,'receipt'),provenance:join(root,'provenance')});
 const bytes=await sharp({create:{width:32,height:32,channels:3,background:'blue'}}).png().toBuffer();await store.putBlob('a'.repeat(64),bytes,'image/png');
 await expect(source.complete(job.id,claim.leaseId,{blobKey:'a'.repeat(64),width:32,height:32,mime:'image/png'})).rejects.toThrow('hash');
 const key=await hash(bytes);await store.putBlob(key,bytes,'image/png');await expect(source.complete(job.id,claim.leaseId,{blobKey:key,width:64,height:32,mime:'image/png'})).rejects.toThrow('dimensions');
});

it('keeps an acknowledged old reservation intact while claiming a new retry',async()=>{
 const root=await mkdtemp(join(tmpdir(),'iq-reviewed-reservation-'));roots.push(root);
 await copyFile(resolve('docs/protocol/worker.py'),join(root,'worker.py'));await writeFile(join(root,'images-todo.md'),'# Image requests\n');
 const store=new MemoryStorage();
 const original={id:'IMG-old-reviewed',prompt:'A square',source:'queue',status:'queued',width:32,height:32,transparent:false,referenceIds:[]} as unknown as Job;
 await appendQueue(root,original,[]);await store.put('jobs',original.id,original);
 const legacy=queueWorkerSource(store,{queueRoot:root,workerId:'legacy-chat',model:'gpt-6.1-sol',effort:'low'});
 await legacy.claim('legacy-chat',['codex-image']);
 const retry={...original,id:'IMG-explicit-retry'};await appendQueue(root,retry,[]);await store.put('jobs',retry.id,retry);
 const local=queueWorkerSource(store,{queueRoot:root,workerId:'local:new',model:'gpt-6.1-sol',effort:'low'});
 expect(await local.hasPending()).toBe(false);
 await store.put('jobs',original.id,{...original,status:'uncertain'});
 expect(await local.hasPending()).toBe(false);
 await store.put('jobs',original.id,{...original,status:'running',claim:{owner:'legacy-chat',reserved:true,since:new Date().toISOString()}});
 const {inspectReservedResult}=await import('../src/core/reservation-recovery');
 await inspectReservedResult(store,{id:original.id,acknowledgeUncertain:true});
 const reviewed=(await store.get<Job>('jobs',original.id))!;
 await store.put('jobs',original.id,{...reviewed,claim:{...reviewed.claim!,owner:'different-worker'}});
 expect(await local.hasPending()).toBe(false);
 await store.put('jobs',original.id,reviewed);
 expect(await local.hasPending()).toBe(true);
 expect((await local.claim('local:new',['codex-image']))?.job.id).toBe(retry.id);
 const {readFile}=await import('node:fs/promises');
 const oldClaim=JSON.parse(await readFile(join(root,'out/.claims',original.id+'.json'),'utf8'));
 expect(oldClaim).toMatchObject({worker:'legacy-chat',state:'reserved'});
});

